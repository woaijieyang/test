def require_clean_encoding_dtype(expected, actual):
    """Fail closed if inference uses a different dtype than the Moment cache.

    The old inference bundle format may omit this field; a staged training
    protocol generated by bootstrap must always provide it.
    """
    if expected is None:
        return
    name = str(actual).removeprefix('torch.')
    if expected not in ('float16', 'bfloat16', 'float32'):
        raise ValueError('unsupported clean moment encoding dtype')
    if expected != name:
        raise ValueError(f'clean moment encoding dtype mismatch: {name} != {expected}')


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':'), allow_nan=False)


def identity(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def training_path(path, evaluation_root=EVAL_ROOT):
    p, root = Path(path).resolve(), Path(evaluation_root).resolve()
    if p == root or root in p.parents:
        raise ValueError(f'evaluation-only path cannot be used for training: {p}')
    return p


def write_bytes(path, content):
    """Publish a new file atomically, never replace an existing user's artifact."""
    path = training_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.hamlet-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as f:
            f.write(content); f.flush(); os.fsync(f.fileno())
        os.link(name, path)  # atomic fail-if-exists; no check/write race
    finally:
        Path(name).unlink(missing_ok=True)


def write_json(path, value):
    write_bytes(path, (json.dumps(value, ensure_ascii=False, indent=2,
                                 sort_keys=True, allow_nan=False)+'\n').encode())


def write_jsonl(path, rows):
    write_bytes(path, ''.join(canonical(r)+'\n' for r in rows).encode())


def read_records(path):
    path = Path(path)
    opener = gzip.open if path.suffix == '.gz' else open
    with opener(path, 'rt', encoding='utf-8') as f:
        text = f.read()
    if not text.strip():
        return []
    try:
        obj = json.loads(text)
    except json.JSONDecodeError:
        return [json.loads(line) for line in text.splitlines() if line.strip()]
    if isinstance(obj, list):
        return obj
    if isinstance(obj, dict) and 'episodes' in obj:
        return obj['episodes']
    if isinstance(obj, dict):
        return [obj]
    raise ValueError(f'expected JSON objects: {path}')


def new_run_dir(path):
    path = training_path(path)
    path.mkdir(parents=True, exist_ok=False)
    return path


def budget(samples, epochs, batch, world_size, accumulation, cap):
    for name, value in [('samples', samples), ('batch', batch), ('world_size', world_size),
                        ('accumulation', accumulation), ('cap', cap)]:
        if not isinstance(value, int) or isinstance(value, bool) or value < 1:
            raise ValueError(f'{name} must be a positive integer')
    if not math.isfinite(epochs) or epochs <= 0:
        raise ValueError('epochs must be finite and positive')
    effective_batch = batch * world_size * accumulation
    # ceil gives at most one partial final batch; cap prevents unbounded repeats.
    steps = min(cap, max(1, math.ceil(samples * epochs / effective_batch)))
    return dict(samples=samples, effective_batch=effective_batch, max_steps=steps,
                upper_bound_exposures=steps*effective_batch,
                effective_epochs_upper=steps*effective_batch/samples)
