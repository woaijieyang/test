"""Small, exclusive, content-addressed artifacts; no dataset/model side effects."""
from __future__ import annotations
import gzip
import hashlib
import json
import math
import os
import tempfile
from pathlib import Path

EVAL_ROOT = Path('/data/zy/vln/data/checkpoint-choice')
